function enterKingdom() {

    const content = document.getElementById("kingdom-content");

    content.classList.remove("hidden");

    setTimeout(() => {
        content.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });
    }, 100);
}


// ==========================================
// FLOWER BUTTON
// ==========================================

function giveFlowers() {

    const flowers = ["🌷", "🌹", "🌸", "💐", "🌺", "🌼"];

    for (let i = 0; i < 25; i++) {

        const flower = document.createElement("div");

        flower.className = "floating-heart";
        flower.textContent = flowers[
            Math.floor(Math.random() * flowers.length)
        ];

        flower.style.left = Math.random() * 100 + "vw";
        flower.style.fontSize = (20 + Math.random() * 20) + "px";
        flower.style.animationDuration = (3 + Math.random() * 3) + "s";

        document.body.appendChild(flower);

        setTimeout(() => flower.remove(), 6500);
    }
}


